public struct TrustedIntelligenceSource: Hashable, Sendable, Identifiable {
    public let id: String
    public let name: String
    public let organization: String
    public let repository: String
    public let branch: String
    public let path: String
    public let licenseName: String
    public let description: String

    public init(id: String, name: String, organization: String, repository: String, branch: String, path: String, licenseName: String, description: String) {
        self.id = id
        self.name = name
        self.organization = organization
        self.repository = repository
        self.branch = branch
        self.path = path
        self.licenseName = licenseName
        self.description = description
    }
}

